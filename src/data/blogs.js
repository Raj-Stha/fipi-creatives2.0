export function getAllBlogs() {
  return blogs;
}

export function getBlogBySlug(slug) {
  return blogs.find((b) => b.slug === slug) || null;
}

export function getFeaturedBlog() {
  return blogs.find((b) => b.featured) || blogs[0];
}

export function getRelatedBlogs(currentSlug, category, limit = 3) {
  return blogs
    .filter((b) => b.slug !== currentSlug && b.category === category)
    .slice(0, limit)
    .concat(
      blogs
        .filter((b) => b.slug !== currentSlug && b.category !== category)
        .slice(
          0,
          Math.max(
            0,
            limit -
              blogs.filter(
                (b) => b.slug !== currentSlug && b.category === category,
              ).length,
          ),
        ),
    )
    .slice(0, limit);
}
